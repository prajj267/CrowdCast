"""Evaluation tables for doc 16 from pipeline output only (WORKFLOW 7.5.1).

Doc 16 forbids entering results by hand. This tool reads the logged runs and renders every
table of the results section:

- SYNTHETIC forecasting: the one-shot test-split ablation runs registered in
  runs/ablation/finals.json (per_event.csv, statistics.csv, classification.csv, operational.csv
  of each run). Point estimates and CIs come from the PRIMARY seed (2027); the other seeds are
  shown as ranges or as "significant in k of n seeds".
- REAL computer vision: the count evaluation runs (runs/cv_eval/<run>/summary.json) and the
  flow evaluation (runs/cv_eval/flows_*.json) on public datasets.

SYNTHETIC and REAL are never mixed in one table. Output: runs/report/<UTC>/results.md (+
manifest.json); with --doc the block between the GENERATED markers in doc 16 is replaced.

Usage (from backend/, clean tree):
  uv run python -m tools.report [--doc ../DOCUMENTATION/16_MODEL_EVALUATION.md]
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from tools.training.stats import COVERAGE_BAND, PRACTICAL, bootstrap_ci
from tools.training.train import git_commit

ROOT = Path(__file__).resolve().parents[2]
RUNS = ROOT / "runs"
PRIMARY_SEED = 2027
HORIZONS = (5, 15, 30)
DASH = chr(0x2013)  # en dash for ranges in the rendered markdown
BEGIN = "<!-- BEGIN GENERATED by tools.report: do not edit by hand -->"
END = "<!-- END GENERATED -->"
DATASET_LABEL = {
    "test_in_venue/clean": "SYN-clean, test-in-venue (V1/V2)",
    "test_in_venue/noisy": "SYN-noisy, test-in-venue (V1/V2)",
    "test_new_venue/clean": "SYN-clean, new venue V3",
    "test_new_venue/noisy": "SYN-noisy, new venue V3",
}
HYPOTHESES = [  # (label, hypothesis, a, b, metric)
    ("H1 schedule: A3 < A1", "H1", "xgb_A3", "xgb_A1", "mae"),
    ("H2 flows: A2 < A1", "H2", "xgb_A2", "xgb_A1", "mae"),
    ("H3 A1 < B0", "H3", "xgb_A1", "B0", "mae"),
    ("H3 A4 < B0", "H3", "xgb_A4", "B0", "mae"),
    ("H4 neighbours: A4 < A4_NONBR", "H4", "xgb_A4", "xgb_A4_NONBR", "mae"),
    ("H4 neighbours, post-release", "H4", "xgb_A4", "xgb_A4_NONBR", "mae_post_release"),
    ("H4 A4 < A3", "H4", "xgb_A4", "xgb_A3", "mae"),
]
OP_MODELS = ("B0", "xgb_A1", "xgb_A4", "xgb_A4_NONBR")


# ---------------------------------------------------------------------- helpers
def md_table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines) + "\n"


def f(x: Any, d: int = 2) -> str:
    """Fixed decimals; "n/a" for a missing value."""
    if x is None or math.isnan(float(x)):
        return "n/a"
    return f"{float(x):.{d}f}"


def pct(x: Any) -> str:
    return f"{100 * float(x):.1f} %"


def mean_ci(values: np.ndarray, d: int = 2) -> str:
    m, lo, hi = bootstrap_ci(values, stat="mean")
    return f"{f(m, d)} [{f(lo, d)}, {f(hi, d)}]"


def load_finals(path: Path) -> dict[str, dict[int, Path]]:
    """dataset -> seed -> run dir, from the finals registry; checks each manifest."""
    out: dict[str, dict[int, Path]] = {}
    for entry in json.loads(path.read_text(encoding="utf-8")):
        out.setdefault(entry["dataset"], {})[int(entry["seed"])] = path.parent / entry["run"]
    for dataset, seeds in out.items():
        for seed, run in seeds.items():
            m = json.loads((run / "manifest.json").read_text(encoding="utf-8"))
            split, data = dataset.split("/")
            if not (m["final"] and m["split"] == split and m["seed"] == seed):
                raise SystemExit(f"{run}: manifest does not match finals entry {dataset}/{seed}")
            if m["data_origin"] != "SYNTHETIC" or f"SYN-{data}" not in m["data"]:
                raise SystemExit(f"{run}: expected SYNTHETIC SYN-{data}, got {m['data']}")
    return out


def seed_order(seeds: dict[int, Path]) -> list[int]:
    if PRIMARY_SEED not in seeds:
        raise SystemExit(f"primary seed {PRIMARY_SEED} missing")
    return [PRIMARY_SEED, *sorted(s for s in seeds if s != PRIMARY_SEED)]


# ---------------------------------------------------------------------- SYNTHETIC sections
def data_section(finals: dict[str, dict[int, Path]]) -> str:
    rows = []
    for ds in DATASET_LABEL:
        if ds not in finals:
            continue
        seeds = seed_order(finals[ds])
        m = json.loads((finals[ds][PRIMARY_SEED] / "manifest.json").read_text(encoding="utf-8"))
        pe = pd.read_csv(finals[ds][PRIMARY_SEED] / "per_event.csv")
        rows.append(
            [
                DATASET_LABEL[ds],
                str(m["train_events"]),
                str(m["target_events"]),
                str(int(pe[(pe.model == "B0") & (pe.horizon == 15)]["rows"].sum())),
                ", ".join(f"{s}: `{finals[ds][s].name}`" for s in seeds),
                f"`{m['git_commit'][:7]}`",
                m["params"].removeprefix("tuned: "),
            ]
        )
    return md_table(
        [
            "Data (SYNTHETIC)",
            "Train events",
            "Test events",
            "Zone-minutes (h 15)",
            "Runs (seed: run)",
            "Commit",
            "Tuned params",
        ],
        rows,
    )


def accuracy_section(finals: dict[str, dict[int, Path]]) -> str:
    rows = []
    for ds in DATASET_LABEL:
        if ds not in finals:
            continue
        pes = {s: pd.read_csv(p / "per_event.csv") for s, p in finals[ds].items()}
        pe = pes[PRIMARY_SEED]
        for h in HORIZONS:
            g = pe[pe.horizon == h]
            mae = {m: g[g.model == m]["mae"].to_numpy() for m in g.model.unique()}
            a4_seeds = [
                p[(p.horizon == h) & (p.model == "xgb_A4")]["mae"].mean() for p in pes.values()
            ]
            rows.append(
                [
                    DATASET_LABEL[ds],
                    str(h),
                    *[mean_ci(mae[b]) for b in ("B0", "B1", "B2", "B3")],
                    mean_ci(mae["xgb_A4"]),
                    f"{f(min(a4_seeds))}{DASH}{f(max(a4_seeds))}",
                    mean_ci(mae["xgb_A4_NONBR"]),
                    f(1 - mae["xgb_A4"].mean() / mae["B0"].mean(), 3),
                ]
            )
    rows.append(["REAL (staged / event)", "5 / 15 / 30", *["not measured"] * 8])
    return md_table(
        [
            "Data",
            "h (min)",
            "B0",
            "B1",
            "B2",
            "B3",
            "XGB A4",
            "A4 over seeds",
            "XGB A4_NONBR",
            "A4 skill vs B0",
        ],
        rows,
    )


def hypothesis_section(finals: dict[str, dict[int, Path]]) -> str:
    rows = []
    h6 = []
    for ds in DATASET_LABEL:
        if ds not in finals:
            continue
        seeds = seed_order(finals[ds])
        st = {s: pd.read_csv(finals[ds][s] / "statistics.csv") for s in seeds}
        for label, hyp, a, b, metric in HYPOTHESES:
            cells = []
            for h in HORIZONS:
                sel = [
                    t[
                        (t.hypothesis == hyp)
                        & (t.a == a)
                        & (t.b == b)
                        & (t.metric == metric)
                        & (t.horizon == h)
                    ]
                    for t in st.values()
                ]
                if any(len(x) != 1 for x in sel):
                    cells.append("n/a")
                    continue
                p = sel[0].iloc[0]
                n_sig = sum(bool(x.iloc[0]["significant"]) for x in sel)
                n_prac = sum(
                    bool(x.iloc[0]["significant"]) and bool(x.iloc[0]["practical"]) for x in sel
                )
                cells.append(
                    f"{pct(p.median_rel_reduction)} [{pct(p.ci_low)}, {pct(p.ci_high)}], "
                    f"p<sub>Holm</sub> {p.p_holm:.2g}; sig {n_sig}/{len(sel)}, "
                    f"sig+practical {n_prac}/{len(sel)}"
                )
            rows.append([DATASET_LABEL[ds], label, *cells])
        holds = 0
        for s in seeds:
            pe = pd.read_csv(finals[ds][s] / "per_event.csv")
            mean = pe.groupby(["horizon", "model"])["mae"].mean().unstack("model")
            holds += bool(((mean.xgb_A4 <= mean.xgb_A3) & (mean.xgb_A3 <= mean.xgb_A1)).all())
        h6.append([DATASET_LABEL[ds], f"{holds} of {len(seeds)} seeds"])
    return (
        md_table(["Data", "Comparison", "h 5", "h 15", "h 30"], rows)
        + "\nH6 (mean MAE ranking A4 ≤ A3 ≤ A1 at every horizon):\n\n"
        + md_table(["Data", "Ranking holds"], h6)
    )


def coverage_section(finals: dict[str, dict[int, Path]]) -> str:
    rows = []
    for ds in DATASET_LABEL:
        if ds not in finals:
            continue
        seeds = seed_order(finals[ds])
        pes = {s: pd.read_csv(finals[ds][s] / "per_event.csv") for s in seeds}
        in_band = []
        for s in seeds:
            q = pes[s][pes[s].model.str.startswith("xgb_")]
            cov = q.groupby(["horizon", "model"])["coverage_conformal"].mean()
            in_band.append(f"{int(cov.between(*COVERAGE_BAND).sum())}/{len(cov)}")
        pe = pes[PRIMARY_SEED]
        for h in HORIZONS:
            g = pe[(pe.horizon == h) & (pe.model == "xgb_A4")]
            rows.append(
                [
                    DATASET_LABEL[ds],
                    str(h),
                    mean_ci(g["coverage_conformal"].to_numpy(), 3),
                    f(g["width_conformal"].mean(), 1),
                    mean_ci(g["coverage_p10_p90"].to_numpy(), 3),
                    ", ".join(in_band) if h == HORIZONS[0] else "",
                ]
            )
    return md_table(
        [
            "Data",
            "h (min)",
            "A4 conformal coverage [95 % CI]",
            "A4 mean width (persons)",
            f"A4 raw P10{DASH}P90 coverage",
            f"XGB cells in {COVERAGE_BAND[0]}{DASH}{COVERAGE_BAND[1]} per seed",
        ],
        rows,
    )


def classification_section(finals: dict[str, dict[int, Path]]) -> str:
    rows = []
    for ds in DATASET_LABEL:
        if ds not in finals:
            continue
        cl = pd.read_csv(finals[ds][PRIMARY_SEED] / "classification.csv")
        for h in HORIZONS:
            g = cl[cl.horizon == h].set_index("model")
            cells = [
                f"{f(g.loc[m, 'f1'], 3)} [{f(g.loc[m, 'f1_ci_low'], 3)}, "
                f"{f(g.loc[m, 'f1_ci_high'], 3)}]"
                for m in OP_MODELS
            ]
            a4 = g.loc["xgb_A4"].to_dict()
            rows.append(
                [
                    DATASET_LABEL[ds],
                    str(h),
                    str(int(a4["positives"])),
                    *cells,
                    f"{f(a4['precision'], 3)} / {f(a4['recall'], 3)}",
                ]
            )
    return md_table(
        ["Data", "h (min)", "Positives", "F1 B0", "F1 A1", "F1 A4", "F1 A4_NONBR", "A4 P / R"],
        rows,
    )


def operational_section(finals: dict[str, dict[int, Path]]) -> str:
    rows = []
    for ds in DATASET_LABEL:
        if ds not in finals:
            continue
        seeds = seed_order(finals[ds])
        ops = {s: pd.read_csv(finals[ds][s] / "operational.csv").set_index("model") for s in seeds}
        op = ops[PRIMARY_SEED]
        for m in OP_MODELS:
            o = op.loc[m].to_dict()
            missed = [float(ops[s].loc[m].to_dict()["missed_rate"]) for s in seeds]
            rows.append(
                [
                    DATASET_LABEL[ds],
                    m,
                    str(int(o["episodes"])),
                    pct(o["missed_rate"]),
                    f"{pct(min(missed))}{DASH}{pct(max(missed))}",
                    f"{f(o['lead_median'], 1)} [{f(o['lead_q25'], 1)}, {f(o['lead_q75'], 1)}]",
                    str(int(o["alerts"])),
                    f(o["false_alarm_rate"], 3),
                    f(o["false_alarms_per_hour"], 3),
                    " / ".join(
                        pct(o[c]) for c in ("first_P30", "first_P15", "first_P5", "first_CURRENT")
                    ),
                ]
            )
    return md_table(
        [
            "Data",
            "Model",
            "Episodes",
            "Missed",
            "Missed over seeds",
            "Lead min, median [IQR]",
            "Alerts",
            "False-alarm rate",
            "False alarms / h",
            "First warning P30 / P15 / P5 / CURRENT",
        ],
        rows,
    )


# ---------------------------------------------------------------------- REAL sections
def cv_count_section(summaries: list[Path]) -> str:
    rows = []
    for path in summaries:
        s = json.loads(path.read_text(encoding="utf-8"))
        for dataset, configs in s["results"].items():
            for config, bands in configs.items():
                for band, r in bands.items():
                    rows.append(
                        [
                            dataset,
                            config,
                            band,
                            str(r["n"]),
                            f(r["mean_true"], 1),
                            f(r["mae"]),
                            f(r["rmse"]),
                            f(r["bias"]),
                            f(r["relative_mae"], 3),
                            f"`{s['run']}`",
                        ]
                    )
    return md_table(
        [
            "Dataset",
            "Detector",
            "Band (true count)",
            "n",
            "Mean true",
            "MAE",
            "RMSE",
            "Bias",
            "Relative MAE",
            "Run",
        ],
        rows,
    )


def cv_flow_section(flow_files: list[Path]) -> str:
    rows = []
    for path in flow_files:
        d = json.loads(path.read_text(encoding="utf-8"))
        for r in d["results"]:
            true = sum(r["true_crossings"].values())
            est = sum(r["est_crossings"].values())
            rows.append(
                [
                    r["sequence"],
                    f(r["length_s"], 1),
                    str(true),
                    str(est),
                    "n/a" if r["precision"] is None else f(r["precision"], 3),
                    f(r["recall_p_det"], 3),
                    f"{r['net_flow']['true']} / {r['net_flow']['estimated']}",
                    str(r["net_flow"]["bias"]),
                    f"`{path.stem}`",
                ]
            )
    return md_table(
        [
            "Sequence",
            "Length (s)",
            "True crossings",
            "Detected",
            "Precision",
            "Recall",
            "Net flow true / est.",
            "Net-flow bias",
            "Run",
        ],
        rows,
    )


# ---------------------------------------------------------------------- assembly
def render(
    finals: dict[str, dict[int, Path]],
    cv_summaries: list[Path],
    flow_files: list[Path],
    commit: str,
) -> str:
    return (
        f"Generated by `tools.report` at commit `{commit[:7]}` from the runs named in each table; "
        "every run has a row in `EXPERIMENT_LOG.md`. **Synthetic and real results are in separate "
        "tables.** Forecasting numbers are SYNTHETIC evidence only: there is no REAL forecasting "
        "dataset (D6).\n\n"
        "### 9.1 Forecasting data (SYNTHETIC, test splits, each evaluated once)\n\n"
        f"{data_section(finals)}\n"
        f"Point estimates and 95 % CIs (bootstrap over events) are from seed {PRIMARY_SEED}; "
        "the other seeds change only the XGBoost seed (data, splits and baselines are identical) "
        "and are shown as ranges or counts.\n\n"
        "### 9.2 Forecast accuracy: mean per-event MAE (persons) [95 % CI]\n\n"
        "RF, LSTM (A4) and GNN (A5) were not run (RF optional, LSTM and GNN are extensions).\n\n"
        f"{accuracy_section(finals)}\n"
        "### 9.3 Hypothesis tests (one-sided Wilcoxon over events, Holm across horizons)\n\n"
        f"Cell: median per-event relative MAE reduction [95 % CI] and Holm p for seed "
        f"{PRIMARY_SEED}; then the number of seeds in which the comparison is significant, and "
        f"significant with a median reduction ≥ {PRACTICAL:.0%} (practical threshold).\n\n"
        f"{hypothesis_section(finals)}\n"
        f"### 9.4 Interval coverage (H7; nominal 0.80, band 0.75{DASH}0.85)\n\n"
        f"{coverage_section(finals)}\n"
        "### 9.5 Congestion classification: ≥ HIGH at t + h (F1 [95 % CI over events])\n\n"
        f"{classification_section(finals)}\n"
        "### 9.6 Operational evaluation: alert replay through `risk.alerts.decide`\n\n"
        f"{operational_section(finals)}\n"
        "### 9.7 Counting accuracy (REAL, public datasets)\n\n"
        "Bands by true count per image or region (areas not calibrated, §2.1).\n\n"
        f"{cv_count_section(cv_summaries)}\n"
        "### 9.8 Line-crossing flows (REAL, MOT20)\n\n"
        f"{cv_flow_section(flow_files)}"
    )


def replace_block(doc: str, block: str) -> str:
    if doc.count(BEGIN) != 1 or doc.count(END) != 1 or doc.index(BEGIN) > doc.index(END):
        raise SystemExit("doc must contain exactly one BEGIN/END GENERATED marker pair")
    head, rest = doc.split(BEGIN)
    _, tail = rest.split(END)
    return f"{head}{BEGIN}\n\n{block}\n{END}{tail}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--finals", type=Path, default=RUNS / "ablation" / "finals.json")
    parser.add_argument("--cv-dir", type=Path, default=RUNS / "cv_eval")
    parser.add_argument("--doc", type=Path, help="doc 16 to update between the markers")
    args = parser.parse_args(argv)
    commit = git_commit()
    if commit.endswith("(dirty working tree)"):
        print("uncommitted changes: commit first (results must come from committed code)")
        return 2
    finals = load_finals(args.finals)
    cv_summaries = sorted(args.cv_dir.glob("*/summary.json"))
    flow_files = sorted(args.cv_dir.glob("flows_*.json"))
    block = render(finals, cv_summaries, flow_files, commit)
    out = RUNS / "report" / datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ")
    out.mkdir(parents=True)
    (out / "results.md").write_text(block, encoding="utf-8", newline="\n")
    manifest: dict[str, Any] = {
        "git_commit": commit,
        "finals": {ds: {str(s): p.name for s, p in v.items()} for ds, v in finals.items()},
        "cv_summaries": [p.parent.name for p in cv_summaries],
        "flow_files": [p.name for p in flow_files],
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=1), encoding="utf-8")
    if args.doc:
        args.doc.write_text(
            replace_block(args.doc.read_text(encoding="utf-8"), block),
            encoding="utf-8",
            newline="\n",
        )
        print(f"updated {args.doc}")
    print(f"written {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
