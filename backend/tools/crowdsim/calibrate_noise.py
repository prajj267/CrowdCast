"""Calibrate the noise model from the logged public-data runs (WORKFLOW 7.2.2; doc 12 §5.3).

Occupancy (m0, m1, sigma_r): per-sample counts of the deployed detector setup (YOLOX-s tiled)
from the 7.1.2 counting runs, all four datasets pooled; density from doc 16's count-band pairing
(an assumption, see tools/crowdsim/noise.py).
Crossings (p_det, r_fp): from the 7.1.3 MOT20 flow run, pooling the sequences' crossings.
Writes configs/crowdsim/noise_calibrated.yaml with the provenance of every value.

Usage (from backend/):
  uv run python -m tools.crowdsim.calibrate_noise --count-runs RUN RUN --flow-run FILE
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import pandas as pd
import yaml

from crowdcast.common.config import REPO_ROOT
from tools.crowdsim.noise import calibrate_occupancy

OUT = REPO_ROOT / "configs" / "crowdsim" / "noise_calibrated.yaml"
CONFIG = "yolox_s_tiled"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--count-runs", nargs="+", required=True)
    parser.add_argument("--flow-run", type=Path, required=True)
    args = parser.parse_args(argv)
    runs = REPO_ROOT / "runs" / "cv_eval"
    samples = pd.concat([pd.read_csv(runs / r / "samples.csv") for r in args.count_runs])
    m0, m1, sigma_r = calibrate_occupancy(samples["true"].tolist(), samples[CONFIG].tolist())

    flows = json.loads((REPO_ROOT / args.flow_run).read_text(encoding="utf-8"))["results"]
    n_true = sum(r["true_crossings"]["down"] + r["true_crossings"]["up"] for r in flows)
    matched = sum(
        r["true_crossings"]["down"] + r["true_crossings"]["up"] - r["missed"] for r in flows
    )
    false = sum(r["false_crossings"] for r in flows)
    minutes = sum(r["length_s"] for r in flows) / 60
    p_det = matched / n_true
    r_fp = false / minutes
    r_fp_upper = (3.0 if false == 0 else float("nan")) / minutes  # rule of three, 95 %

    data = {
        "noise_model": "doc 12 §5.3",
        "m0": round(m0, 4),
        "m1": round(m1, 4),
        "sigma_r": round(sigma_r, 4),
        "p_det": round(p_det, 4),
        "r_fp": round(r_fp, 4),
        "provenance": {
            "occupancy": f"calibrated: {len(samples)} samples, detector {CONFIG}, runs "
            f"{', '.join(args.count_runs)} (REAL public: Mall, ShanghaiTech B, MOT20-01/03); "
            "density taken from doc 16 §2.1 count-band <-> density-band pairing "
            "(band midpoints) - an ASSUMPTION, areas are not calibrated",
            "crossings": f"calibrated: {n_true} true crossings, {matched} detected, {false} false "
            f"in {minutes:.1f} min, run {args.flow_run.name} (MOT20-01/03 virtual line); "
            f"r_fp 95 % upper bound {r_fp_upper:.2f} per min (rule of three); "
            "p_det comes almost entirely from one scene (MOT20-03)",
        },
    }
    OUT.write_text(
        "# Calibrated observation-noise parameters (WORKFLOW 7.2.2). Generated by\n"
        "# tools/crowdsim/calibrate_noise.py from logged runs - do not edit by hand.\n"
        + yaml.safe_dump(data, sort_keys=False, width=100),
        encoding="utf-8",
    )
    print(json.dumps(data, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
